import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;

public class AIHelper {

    // The first model is tried first; if it fails, the second one is used
    static final String[] MODELS = {"gemini-3.8-flash", "gemini-3.6-flash"};

    static final String[] DEPARTMENTS = {
        "Emergency", "Cardiology", "Neurology",
        "Orthopedics", "Pediatrics", "Reception"
    };

    public static String suggestDepartment(String symptoms) {
        String key = System.getenv("GEMINI_API_KEY");
        if (key == null || key.isEmpty()) {
            System.out.println("(API key not found, using keyword-based fallback)");
            return keywordGuess(symptoms);
        }

        String prompt = "You are a hospital triage assistant. Patient symptoms: "
                + symptoms
                + ". Choose ONE department from this list: Emergency, Cardiology, "
                + "Neurology, Orthopedics, Pediatrics, Reception (for general cases). "
                + "Reply with only the department name and nothing else.";

        for (String model : MODELS) {
            String answer = askGemini(model, key, prompt);
            if (answer != null) {
                for (String dept : DEPARTMENTS) {
                    if (answer.toLowerCase().contains(dept.toLowerCase())) {
                        System.out.println("(Response generated by Gemini AI)");
                        return dept;
                    }
                }
            }
        }

        System.out.println("(Gemini AI unavailable, using keyword-based fallback)");
        return keywordGuess(symptoms);
    }

    // Ask one model. Returns null if anything goes wrong
    private static String askGemini(String model, String key, String prompt) {
        try {
            String body = "{\"contents\":[{\"parts\":[{\"text\":\"" + escape(prompt) + "\"}]}]}";

            HttpRequest request = HttpRequest.newBuilder()
                    .uri(URI.create("https://generativelanguage.googleapis.com/v1beta/models/"
                            + model + ":generateContent"))
                    .header("Content-Type", "application/json")
                    .header("x-goog-api-key", key)
                    .POST(HttpRequest.BodyPublishers.ofString(body))
                    .build();

            HttpClient client = HttpClient.newHttpClient();
            HttpResponse<String> response = client.send(request, HttpResponse.BodyHandlers.ofString());

            if (response.statusCode() != 200) {
                System.out.println("(" + model + " returned error code " + response.statusCode() + ")");
                return null;
            }
            return extractText(response.body());

        } catch (Exception e) {
            System.out.println("(" + model + ": network or connection problem)");
            return null;
        }
    }

    private static String escape(String text) {
        return text.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", " ");
    }

    // Extracts the "text" value from the AI's JSON reply
    private static String extractText(String json) {
        int i = json.indexOf("\"text\"");
        if (i == -1) {
            return "";
        }
        int start = json.indexOf("\"", json.indexOf(":", i)) + 1;
        StringBuilder result = new StringBuilder();
        for (int k = start; k < json.length(); k++) {
            char c = json.charAt(k);
            if (c == '\\') {
                k++;
            } else if (c == '"') {
                break;
            } else {
                result.append(c);
            }
        }
        return result.toString();
    }

    // Fallback: simple keyword matching when the AI is unavailable
    public static String keywordGuess(String symptoms) {
        String s = symptoms.toLowerCase();
        if (s.contains("accident") || s.contains("bleeding") || s.contains("unconscious")
                || s.contains("burn") || s.contains("poison") || s.contains("choking")
                || s.contains("khoon") || s.contains("behosh")) {
            return "Emergency";
        }
        if (s.contains("chest") || s.contains("heart") || s.contains("palpitation")
                || s.contains("breath") || s.contains("seene")) {
            return "Cardiology";
        }
        if (s.contains("head") || s.contains("migraine") || s.contains("dizz")
                || s.contains("seizure") || s.contains("numb") || s.contains("sar dard")
                || s.contains("sar m") || s.contains("chakkar")) {
            return "Neurology";
        }
        if (s.contains("bone") || s.contains("fracture") || s.contains("joint")
                || s.contains("knee") || s.contains("back pain") || s.contains("sprain")
                || s.contains("haddi") || s.contains("kamar")) {
            return "Orthopedics";
        }
        if (s.contains("child") || s.contains("baby") || s.contains("infant")
                || s.contains("kid") || s.contains("bachch")) {
            return "Pediatrics";
        }
        return "Reception";
    }
}
